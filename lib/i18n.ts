export const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { de, it };

export function translate(lang: Language, key: TranslationKey, params?: Record<string, string | number>) {
  const text = DICTIONARIES[lang][key] ?? DICTIONARIES.de[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}
